/* The service worker: UFMWiz offline.
   ------------------------------------------------------------------
   A second cache on top of the browser's, and the two have to agree or the
   site breaks the worst way it can: half of it this release, half the last.
   So, as on FHCWiz:

   - The cache name carries the version (SITE.version in js/data/routes.js).
     A release is a new cache, and activate deletes every older one. Nothing
     is ever served from the previous release's cache.
   - PRECACHE is GENERATED by tools/sw.mjs from the built site: every page,
     every module, every icon. A hand-kept list drifts, and a drifted list is
     what serves new CSS against old JavaScript.
   - Pages go to the network first and fall back to the cache, so the HTML is
     fresh whenever there is a connection, and still opens when there isn't.
   - A stamped asset (?v=<version>) is cache-first: its URL changes whenever
     its bytes do, so the cached copy can't be the wrong one. Everything else
     of ours, including the modules the app imports without a stamp, is
     network-first with the cache behind it.
   - Other origins are never intercepted, with one exception: Google Fonts,
     in a cache of their own that outlives releases, because the font files
     don't change when we ship and without them the display face falls back
     to a system sans the moment the network goes.
   - The precache is fetched past the browser's HTTP cache, so a new release
     can't be installed out of stale copies of the old one. */

