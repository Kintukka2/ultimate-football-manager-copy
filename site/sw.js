const SHELL = 'ufmwiz-shell-v' + VERSION;
const FONTS = 'ufmwiz-fonts';
const SCOPE = self.registration ? self.registration.scope : self.location.href.replace(/sw\.js$/, '');
const at = (p) => new URL(p, SCOPE).href;

// On a development server a stamp stays the same while the file under it
// changes, so there everything is network-first and an edit shows on reload.
const LOCAL = /^(localhost|127\.0\.0\.1|\[::1\])$/.test(self.location.hostname);

const isFont = (url) => url.host === 'fonts.googleapis.com' || url.host === 'fonts.gstatic.com';
const isStamped = (url) => /\/(css|js)\//.test(url.pathname) && url.searchParams.has('v');

self.addEventListener('install', (e) => {
  e.waitUntil(
    caches.open(SHELL)
      // All or nothing: a half-filled shell would open some pages offline and
      // fail on others, with no pattern a reader could learn.
      .then((cache) => cache.addAll(PRECACHE.map((p) => new Request(at(p), { cache: 'reload' }))))
      // Safe to take over at once, because the cache is version-keyed.
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((names) => Promise.all(names
        // Ours, from an earlier release. The font cache belongs to no release.
        .filter((n) => n.startsWith('ufmwiz-shell-') && n !== SHELL)
        .map((n) => caches.delete(n))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) {
    if (isFont(url)) e.respondWith(fontFirst(req));
    return;
  }
  if (req.mode === 'navigate') { e.respondWith(page(req)); return; }
  if (isStamped(url) && !LOCAL) { e.respondWith(cacheFirst(req)); return; }
  e.respondWith(networkFirst(req));
});

function keep(req, res) {
  if (res && res.ok && res.type === 'basic') {
    const copy = res.clone();
    caches.open(SHELL).then((c) => c.put(req, copy));
  }
  return res;
}

function cacheFirst(req) {
  return caches.match(req).then((hit) => hit || fetch(req).then((res) => keep(req, res)));
}

function networkFirst(req) {
  return fetch(req).then((res) => keep(req, res)).catch(() =>
    caches.match(req).then((hit) => hit || Response.error()));
}

// A page we have never held, with no connection to fetch it, gets the
// not-found page rather than the browser's own error.
function page(req) {
  return fetch(req).then((res) => keep(req, res)).catch(() =>
    caches.match(req, { ignoreSearch: true })
      .then((hit) => hit || caches.match(at('404.html')))
      .then((hit) => hit || Response.error()));
}

// A font arrives opaque, so `ok` can't be read. Keep it anyway: a font either
// renders or it doesn't, and a bad one costs a fallback face, not the site.
function fontFirst(req) {
  return caches.match(req).then((hit) => hit || fetch(req).then((res) => {
    const copy = res.clone();
    caches.open(FONTS).then((c) => c.put(req, copy));
    return res;
  }));
}
