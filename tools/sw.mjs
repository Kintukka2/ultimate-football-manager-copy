// Writes the service worker's precache list from the built site, keyed to
// the site version. The list is generated rather than kept by hand because a
// list that drifts from the pages is what serves one release's CSS against
// another's JavaScript (see the header of site/sw.js).
//
//   node tools/sw.mjs           rewrite the PRECACHE region of site/sw.js
//   node tools/sw.mjs --check   exit 1 if it is out of date, write nothing
//
// tools/build.mjs calls writeServiceWorker() after writing the pages, so the
// list always matches what was just built.

import { readFile, writeFile, readdir } from 'node:fs/promises';
import { join, relative, dirname, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', 'site');

// Served at the root but never needed offline: crawler files, the social
// card, host config and the worker itself.
const SKIP = /^(sw\.js|og\.png|robots\.txt|sitemap\.xml|_headers|_redirects|[0-9a-f]{32}\.txt)$/;
const ICON = /^(icon[\w-]*\.(png|svg)|apple-touch-icon\.png|manifest\.json)$/;

async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...await walk(p));
    else out.push(p);
  }
  return out;
}

const web = (p) => relative(ROOT, p).split(sep).join('/');

// Every page (as the address a reader opens), every asset a page links with
// its stamp, every module without one (the app imports its modules
// unstamped; stylesheets are only ever linked stamped), the card data, the
// manifest and the icons.
export async function precacheList(root = ROOT) {
  const files = (await walk(root)).map((p) => relative(root, p).split(sep).join('/'));
  const list = new Set();
  for (const f of files) {
    if (SKIP.test(f)) continue;
    if (f.endsWith('index.html')) list.add(f.slice(0, -'index.html'.length));
    else if (f === '404.html' || ICON.test(f) || /^js\/.+\.js$/.test(f) || /^data\/.+\.json$/.test(f)) list.add(f);
  }
  for (const f of files.filter((x) => x.endsWith('.html'))) {
    const html = await readFile(join(root, f), 'utf8');
    for (const m of html.matchAll(/\s(?:href|src)="((?:css|js)\/[^"#]+\?v=[^"#]+)"/g)) list.add(m[1]);
  }
  // The root sorts first as '', then the rest in path order, so a diff of the
  // worker reads like a diff of the site.
  return [...list].sort((a, b) => (a === '' ? -1 : b === '' ? 1 : a < b ? -1 : a > b ? 1 : 0));
}

export function region(version, list) {
  return '/* PRECACHE:START — generated by tools/sw.mjs, do not edit by hand */\n'
    + `const VERSION = '${version}';\n`
    + `const PRECACHE = [\n${list.map((p) => `  '${p}',`).join('\n')}\n];\n`
    + '/* PRECACHE:END */';
}

// Returns { changed, count }. With check, writes nothing.
export async function writeServiceWorker({ root = ROOT, version, check = false } = {}) {
  if (!version) ({ SITE: { version } } = await import(pathToFileURL(join(root, 'js/data/routes.js')).href));
  const file = join(root, 'sw.js');
  const src = await readFile(file, 'utf8');
  const re = /\/\* PRECACHE:START[\s\S]*?PRECACHE:END \*\//;
  if (!re.test(src)) throw new Error('site/sw.js has lost its PRECACHE markers');
  const list = await precacheList(root);
  const next = src.replace(re, region(version, list));
  const changed = next !== src;
  if (changed && !check) await writeFile(file, next);
  return { changed, count: list.length, version };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const check = process.argv.includes('--check');
  const r = await writeServiceWorker({ check });
  if (check && r.changed) {
    console.error(`sw: the precache list in site/sw.js is out of date for v${r.version}. Run node tools/build.mjs (or node tools/sw.mjs).`);
    process.exit(1);
  }
  console.log(`sw: ${r.count} entries for v${r.version}${r.changed ? (check ? '' : ', written') : ', unchanged'}`);
}
